/**
 * Regenerates src/app/shared/ui/icons.data.ts from Lucide's published SVGs.
 *
 * The icons are copied in, not installed: the app uses a few dozen of Lucide's
 * thousand-odd, and a dependency for that would put its whole release cadence in the
 * update queue. To add an icon, add its name to NAMES and run:
 *
 *   npm pack lucide-static@<version>          # in any scratch folder
 *   tar -xzf lucide-static-<version>.tgz
 *   node scripts/icons.mjs <that folder>/package
 *
 * Lucide is ISC-licensed; its notice is in docs/third-party-assets.md, which a copy
 * requires.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const NAMES = [
  'arrow-left',
  'arrow-right',
  'badge-check',
  'building-2',
  'calendar',
  'camera',
  'car-front',
  'check',
  'chevron-down',
  'clock',
  'cog',
  'fuel',
  'gauge',
  'heart',
  'history',
  'image',
  'leaf',
  'map-pin',
  'message-circle',
  'mountain',
  'plug-zap',
  'search',
  'shield-check',
  'sliders-horizontal',
  'store',
  'user',
  'users',
  'x',
  'zap',
];

/** The element types Lucide draws with — and the only ones the Icon component renders. */
const ELEMENTS = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/icons.mjs <path to an unpacked lucide-static package>');
  process.exit(1);
}

const pkg = JSON.parse(readFileSync(join(source, 'package.json'), 'utf8'));
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const entries = NAMES.map((name) => {
  const svg = readFileSync(join(source, 'icons', `${name}.svg`), 'utf8');
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '');
  const nodes = [...body.matchAll(/<(\w+)([^>]*?)\/?>/g)].map(([, tag, attributes]) => {
    if (!ELEMENTS.has(tag)) {
      throw new Error(`${name}.svg: <${tag}> is not an element the Icon component renders`);
    }
    const attrs = Object.fromEntries([...attributes.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]));
    return [tag, attrs];
  });
  return [name, nodes];
});

const lines = [
  '// GENERATED by scripts/icons.mjs from lucide-static ' + pkg.version + ' (' + pkg.license + ').',
  '// Do not edit by hand: add the name to the script and run it again.',
  '// Licence notice: docs/third-party-assets.md.',
  '',
  "import type { IconNode } from './icon';",
  '',
  'export const ICONS = {',
  ...entries.map(([name, nodes]) => `  '${name}': ${JSON.stringify(nodes)},`),
  '} as const satisfies Record<string, IconNode>;',
  '',
  'export type IconName = keyof typeof ICONS;',
  '',
];
writeFileSync(join(root, 'src/app/shared/ui/icons.data.ts'), lines.join('\n'));
console.log(`wrote ${entries.length} icons from lucide-static ${pkg.version}`);
