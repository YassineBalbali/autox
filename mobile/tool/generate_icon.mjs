// The launcher icon's Android resources, from assets/icon/autox-icon.svg.
//
//   node tool/generate_icon.mjs
//
// Writes, under android/app/src/main/res:
//  - mipmap-anydpi-v26/ic_launcher.xml: the adaptive icon (Android 8+), made of the layers below;
//  - values/ic_launcher_background.xml: the background layer, the SVG rect's colour;
//  - drawable/ic_launcher_foreground.xml: the foreground layer, the SVG's paths unchanged, each in
//    its own colour;
//  - drawable/ic_launcher_monochrome.xml: the same paths in one colour, for Android 13's themed
//    icons, which keep only the layer's shape and tint it;
//  - mipmap-*dpi/ic_launcher.png: the icon for Android 7 (minSdk 24), which has no adaptive
//    icons: the background in a rounded square with the paths on it, drawn here.
// and assets/icon/autox-icon-512.png, the full square (a store listing's size).
//
// No dependencies: the paths use only absolute M, L and Z, filled with 4×4 samples per pixel,
// and the PNGs are written with node:zlib.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateSync } from 'node:zlib';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const res = join(root, 'android/app/src/main/res');
const svg = readFileSync(join(root, 'assets/icon/autox-icon.svg'), 'utf8');

const attr = (element, name) => {
  const value = new RegExp(`\\s${name}="([^"]*)"`).exec(element)?.[1];
  if (value === undefined) throw new Error(`no ${name} in ${element}`);
  return value;
};
const rect = /<rect id="background"[^>]*>/.exec(svg)?.[0];
if (!rect) throw new Error('autox-icon.svg: no rect with id="background"');
const background = attr(rect, 'fill');
// Painted in document order: a later path covers an earlier one.
const paths = [...svg.matchAll(/<path\b[^>]*>/g)].map(([element]) => ({
  fill: attr(element, 'fill'),
  d: attr(element, 'd'),
}));
if (paths.length === 0) throw new Error('autox-icon.svg: no path');
if (/transform=/.test(svg)) throw new Error('autox-icon.svg: transforms are not supported');

// ---- the Android resources ---------------------------------------------------------------

const write = (path, content) => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
};
const generated = '<!-- Generated by tool/generate_icon.mjs from assets/icon/autox-icon.svg. Do not edit. -->';
const vector = (fillOf) => `<?xml version="1.0" encoding="utf-8"?>
${generated}
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
${paths
  .map(
    (path) => `    <path
        android:fillColor="${fillOf(path)}"
        android:pathData="${path.d}" />`,
  )
  .join('\n')}
</vector>
`;

write(join(res, 'drawable/ic_launcher_foreground.xml'), vector((path) => path.fill));
// Any opaque colour: the launcher replaces it with the theme's.
write(join(res, 'drawable/ic_launcher_monochrome.xml'), vector(() => '#ff000000'));
write(
  join(res, 'values/ic_launcher_background.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
${generated}
<resources>
    <color name="ic_launcher_background">${background}</color>
</resources>
`,
);
write(
  join(res, 'mipmap-anydpi-v26/ic_launcher.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
${generated}
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`,
);

// ---- the paths, as polygons in the 108-unit canvas ---------------------------------------

function polygonsOf(pathData) {
  const tokens = pathData.match(/[A-Za-z]|-?(?:\d+\.?\d*|\.\d+)/g);
  const polygons = [];
  let current = [];
  let command = null;
  let index = 0;
  const number = () => Number(tokens[index++]);
  while (index < tokens.length) {
    if (/[A-Za-z]/.test(tokens[index])) {
      command = tokens[index++];
      if (!/[MLZ]/.test(command)) throw new Error(`path command ${command} not supported`);
    }
    if (command === 'M') {
      if (current.length) polygons.push(current);
      current = [[number(), number()]];
      command = 'L';
    } else if (command === 'L') {
      current.push([number(), number()]);
    } else if (command === 'Z') {
      if (current.length) polygons.push(current);
      current = [];
    }
  }
  if (current.length) polygons.push(current);
  return polygons;
}

const rgb = (hex) => [1, 3, 5].map((offset) => parseInt(hex.slice(offset, offset + 2), 16));
const shapes = paths.map((path) => ({ colour: rgb(path.fill), polygons: polygonsOf(path.d) }));

function inside(polygons, px, py) {
  let result = false;
  for (const polygon of polygons) {
    for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
      const [xi, yi] = polygon[i];
      const [xj, yj] = polygon[j];
      if (yi > py !== yj > py && px < ((xj - xi) * (py - yi)) / (yj - yi) + xi) result = !result;
    }
  }
  return result;
}

/** The colour at a point of the canvas: the last path covering it, or the background. */
function colourAt(x, y) {
  for (let s = shapes.length - 1; s >= 0; s--) {
    if (inside(shapes[s].polygons, x, y)) return shapes[s].colour;
  }
  return rgb(background);
}

// ---- the PNGs ----------------------------------------------------------------------------

/**
 * The canvas from `from` to `to` (in its 108 units) on `size` pixels, inside a square with
 * corners of `radius` (a fraction of the side); transparent outside it.
 */
function render(size, { from, to, radius }) {
  const pixels = Buffer.alloc(size * size * 4);
  const samples = 4;
  const span = to - from;
  const r = radius * size;
  const inShape = (sx, sy) => {
    const cx = Math.min(Math.max(sx, r), size - r);
    const cy = Math.min(Math.max(sy, r), size - r);
    return (sx - cx) ** 2 + (sy - cy) ** 2 <= r * r;
  };
  for (let py = 0; py < size; py++) {
    for (let px = 0; px < size; px++) {
      let covered = 0;
      const sum = [0, 0, 0];
      for (let j = 0; j < samples; j++) {
        for (let i = 0; i < samples; i++) {
          const sx = px + (i + 0.5) / samples;
          const sy = py + (j + 0.5) / samples;
          if (!inShape(sx, sy)) continue;
          covered++;
          const colour = colourAt(from + (sx / size) * span, from + (sy / size) * span);
          for (let channel = 0; channel < 3; channel++) sum[channel] += colour[channel];
        }
      }
      if (covered === 0) continue;
      const offset = (py * size + px) * 4;
      for (let channel = 0; channel < 3; channel++) pixels[offset + channel] = Math.round(sum[channel] / covered);
      pixels[offset + 3] = Math.round((covered / (samples * samples)) * 255);
    }
  }
  return png(size, pixels);
}

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buffer) {
  let c = 0xffffffff;
  for (const byte of buffer) c = crcTable[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}
function png(size, pixels) {
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header.set([8, 6, 0, 0, 0], 8); // 8 bits, RGBA, deflate, no filter set, no interlace
  const rows = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) pixels.copy(rows, y * (size * 4 + 1) + 1, y * size * 4, (y + 1) * size * 4);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', header),
    chunk('IDAT', deflateSync(rows, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

// Android 7: the central 84 units, so the X is half the icon, in a rounded square.
const legacy = { from: 12, to: 96, radius: 0.18 };
for (const [density, size] of [
  ['mdpi', 48],
  ['hdpi', 72],
  ['xhdpi', 96],
  ['xxhdpi', 144],
  ['xxxhdpi', 192],
]) {
  write(join(res, `mipmap-${density}/ic_launcher.png`), render(size, legacy));
}
write(join(root, 'assets/icon/autox-icon-512.png'), render(512, { from: 12, to: 96, radius: 0 }));
console.log('Launcher icon written from assets/icon/autox-icon.svg.');
